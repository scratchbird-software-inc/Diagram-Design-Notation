/* Re-inlines the public runtime into the root landing page and rebuilds the
 * notation-plates browser with inlined SVGs, so both work as single files
 * under any file:// restriction (document portals, blocked subresources).
 * Run after npm run build:sdk or after changing standard/plates/. */
'use strict';
const fs = require('node:fs'), path = require('node:path');
const root = path.resolve(__dirname, '..');

// --- 1. landing page: inline notation/dist/ddn.global.js between markers ---
const runtime = fs.readFileSync(path.join(root, 'notation/dist/ddn.global.js'), 'utf8');
if (runtime.includes('</script')) throw new Error('runtime contains </script; inlining would break the page');
const landingPath = path.join(root, 'index.html');
let landing = fs.readFileSync(landingPath, 'utf8');
const BEGIN = '<!-- INLINE RUNTIME:BEGIN (generated by tools/build-standalone-pages.js) -->';
const END = '<!-- INLINE RUNTIME:END -->';
const block = BEGIN + '\n<script>\n' + runtime + '\n</script>\n' + END;
if (landing.includes(BEGIN) && landing.includes(END)) {
  landing = landing.slice(0, landing.indexOf(BEGIN)) + block + landing.slice(landing.indexOf(END) + END.length);
} else {
  const tag = '<script src="notation/dist/ddn.global.js"></script>';
  if (!landing.includes(tag)) throw new Error('landing page: no inline markers and no external script tag to replace');
  landing = landing.replace(tag, () => block); // function replacement: no $-pattern expansion
}
fs.writeFileSync(landingPath, landing);
console.log('index.html: runtime inlined,', runtime.length, 'bytes');

// --- 2. plates browser: inline every SVG under standard/plates/ ---
const platesDir = path.join(root, 'standard/plates');
const files = fs.readdirSync(platesDir).filter(f => f.endsWith('.svg')).sort();
if (!files.length) throw new Error('no SVG plates found');
const groups = [['kinds-', 'Object kinds'], ['facets-', 'Facets'], ['relationships-', 'Relationships']];
const groupOf = f => (groups.find(([pre]) => f.startsWith(pre)) || [null, 'Anatomy, looks and routing'])[1];
const order = ['Object kinds', 'Facets', 'Relationships', 'Anatomy, looks and routing'];
const byGroup = new Map(order.map(g => [g, []]));
for (const f of files) byGroup.get(groupOf(f)).push(f);
const inlineSvg = f => fs.readFileSync(path.join(platesDir, f), 'utf8').replace(/<\?xml[^?]*\?>\s*/, '');
const platesHtml = (fs.readFileSync(path.join(__dirname, 'plates-page.template.html'), 'utf8'))
  .replace('{{BODY}}', () => order.map(g =>
    `<h2>${g}</h2>\n` + byGroup.get(g).map(f =>
      `<div class="plate"><h3>${f.replace(/\.svg$/, '')}</h3>${inlineSvg(f)}</div>`).join('\n')
  ).join('\n'))
  .replace('{{COUNT}}', String(files.length));
fs.writeFileSync(path.join(platesDir, 'index.html'), platesHtml);
console.log('standard/plates/index.html: regenerated with', files.length, 'inlined plates');
